#!/usr/bin/env python3
"""Linux stand-in for FidelityFX-SC's glslang path (the SDK ships it only for
Windows). Compiles every permutation of one FidelityFX GLSL pass with
glslc and writes the same <name>_permutations.h the SDK's blob
accessors include.

ffx_sc.py --reflect <tool> --out <dir> --name <name> [-D...] [-DOPT={0,1}] [-I...] <shader.glsl>
"""
import argparse, hashlib, itertools, math, os, re, subprocess, sys, tempfile

KINDS = ["CBV", "TextureSRV", "TextureUAV", "BufferSRV", "BufferUAV", "Sampler", "RTAccelerationStructure"]
MEMBERS = [("numConstantBuffers", "constantBuffer"), ("numSRVTextures", "srvTexture"),
           ("numUAVTextures", "uavTexture"), ("numSRVBuffers", "srvBuffer"), ("numUAVBuffers", "uavBuffer"),
           ("numSamplers", "sampler"), ("numRTAccelerationStructures", "rtAccelerationStructure")]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--reflect", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--name", required=True)
    ap.add_argument("--glslc", default="glslc")
    ap.add_argument("shader")
    args, rest = ap.parse_known_args()

    defines, options, includes = [], [], []
    for a in rest:
        m = re.match(r"-D([A-Za-z0-9_]+)=\{(.*)\}$", a)
        if m:
            options.append((m.group(1), m.group(2).split(",")))
        elif a.startswith("-D"):
            defines.append(a)
        elif a.startswith("-I"):
            includes.append(a)
        else:
            sys.exit("unknown arg " + a)

    # FidelityFX-SC puts options that appear in the shader (or its includes) first;
    # we keep every option and give each its bits in the given order, which is
    # what the union below describes, so keys and table agree either way.
    bits = [max(1, math.ceil(math.log2(len(v)))) if len(v) > 1 else 0 for _, v in options]

    uniques = []  # (header name, reflection), in index order
    table = {}    # permutation key -> index into uniques
    seen = {}     # spirv md5 -> index
    with tempfile.TemporaryDirectory() as tmp:
        for combo in itertools.product(*[range(len(v)) for _, v in options]):
            key, shift, defs = 0, 0, []
            for (opt, vals), i, nb in zip(options, combo, bits):
                key |= i << shift
                shift += nb
                defs.append("-D%s=%s" % (opt, vals[i]))
            spv = os.path.join(tmp, "%d.spv" % key)
            # Same flags as the SDK's glslang call (-S comp, Vulkan 1.2; -O0 because glslc's optimiser drops the binding names the SDK maps resources by), via the NDK's glslc.
            cmd = [args.glslc, "-fshader-stage=compute", "--target-env=vulkan1.2", "-O0",
                   "-DFFX_GLSL=1"] + defines + defs + includes + ["-o", spv, args.shader]
            r = subprocess.run(cmd, capture_output=True, text=True)
            if r.returncode:
                sys.exit("glslang failed: %s\n%s%s" % (" ".join(cmd), r.stdout, r.stderr))
            # The -O0 module is only for reflection; the blob is glslc's optimised one,
            # whose bindings are the same explicit ones (unused ones may be gone).
            opt = spv + ".opt"
            ocmd = [c if c != "-O0" else "-O" for c in cmd[:-3]] + ["-o", opt, args.shader]
            r = subprocess.run(ocmd, capture_output=True, text=True)
            if r.returncode:
                sys.exit("glslc -O failed: %s\n%s%s" % (" ".join(ocmd), r.stdout, r.stderr))
            data = open(opt, "rb").read()
            digest = hashlib.md5(open(spv, "rb").read() + data).hexdigest()
            if digest in seen:
                table[key] = seen[digest]
                continue
            refl = subprocess.run([args.reflect, spv], capture_output=True, text=True, check=True).stdout
            res = {k: [] for k in KINDS}
            for line in refl.splitlines():
                kind, name, binding, count, sett = line.split()
                res[kind].append((name if name != "-" else "", int(binding), int(count), int(sett)))
            pname = "%s_%s" % (args.name, digest)
            with open(os.path.join(args.out, pname + ".h"), "w") as f:
                f.write("// %s.h.\n// Auto generated by ffx_sc.py.\n\n" % pname)
                for kind in KINDS:
                    rs = res[kind]
                    if not rs:
                        continue
                    f.write("static const char* g_%s_%sResourceNames[] = { %s };\n" % (pname, kind, " ".join('"%s",' % r[0] for r in rs)))
                    for idx, suffix in ((1, "Bindings"), (2, "Counts"), (3, "Sets")):
                        f.write("static const uint32_t g_%s_%sResource%s[] = { %s };\n" % (pname, kind, suffix, " ".join("%d," % r[idx] for r in rs)))
                    f.write("\n")
                f.write("static const uint32_t g_%s_size = %d;\n\n" % (pname, len(data)))
                f.write("static const unsigned char g_%s_data[] = {\n" % pname)
                f.write(",\n".join(",".join("0x%02x" % b for b in data[i:i + 16]) for i in range(0, len(data), 16)))
                f.write("\n};\n\n")
            seen[digest] = len(uniques)
            table[key] = len(uniques)
            uniques.append((pname, res))

    with open(os.path.join(args.out, args.name + "_permutations.h"), "w") as f:
        for pname, _ in uniques:
            f.write('#include "%s.h"\n' % pname)
        f.write("\ntypedef union %s_PermutationKey {\n    struct {\n" % args.name)
        for (opt, _), nb in zip(options, bits):
            if nb:
                f.write("        uint32_t %s : %d;\n" % (opt, nb))
        f.write("    };\n    uint32_t index;\n} %s_PermutationKey;\n\n" % args.name)
        f.write("typedef struct %s_PermutationInfo {\n    const uint32_t       blobSize;\n    const unsigned char* blobData;\n\n" % args.name)
        for num, base in MEMBERS:
            f.write("\n    const uint32_t  %s;\n    const char**    %sNames;\n    const uint32_t* %sBindings;\n"
                    "    const uint32_t* %sCounts;\n    const uint32_t* %sSpaces;\n" % (num, base, base, base, base))
        f.write("} %s_PermutationInfo;\n\n" % args.name)
        total = 1 << sum(bits)
        f.write("static const uint32_t g_%s_IndirectionTable[] = {\n" % args.name)
        f.write("".join("    %d,\n" % table.get(i, 0) for i in range(total)))
        f.write("};\n\n")
        f.write("static const %s_PermutationInfo g_%s_PermutationInfo[] = {\n" % (args.name, args.name))
        for pname, res in uniques:
            parts = []
            for kind in KINDS:
                n = len(res[kind])
                parts.append("0, 0, 0, 0, 0, " if not n else
                             "%d, g_%s_%sResourceNames, g_%s_%sResourceBindings, g_%s_%sResourceCounts, g_%s_%sResourceSets, "
                             % (n, pname, kind, pname, kind, pname, kind, pname, kind))
            f.write("    { g_%s_size, g_%s_data, %s},\n" % (pname, pname, "".join(parts)))
        f.write("};\n\n")


if __name__ == "__main__":
    main()
