#!/bin/sh
# Regenerates src/main/cpp/vkwrap/trampolines.{S,inc}: one forwarding stub per
# libvulkan.so export the wrapper does not implement itself.
set -e
NDK=${ANDROID_NDK:-/opt/android-sdk/ndk/29.0.14206865}
BIN=$NDK/toolchains/llvm/prebuilt/linux-x86_64
OUT=$(dirname "$0")/../src/main/cpp/vkwrap
OWN="vkGetInstanceProcAddr vkGetDeviceProcAddr vkCreateInstance vkCreateDevice vkDestroyDevice vkGetDeviceQueue vkGetDeviceQueue2 vkCreateSwapchainKHR vkDestroySwapchainKHR vkQueuePresentKHR vkCreateAndroidSurfaceKHR"
names=$("$BIN/bin/llvm-nm" -D --defined-only "$BIN/sysroot/usr/lib/aarch64-linux-android/34/libvulkan.so" | awk '{print $3}' | grep '^vk' | sort)
{
  echo "// Generated by scripts/gen-vk-trampolines.sh. Do not edit."
  echo "    .text"
  for n in $names; do
    case " $OWN " in *" $n "*) continue ;; esac
    echo "    .globl $n"
    echo "    .type $n, %function"
    echo "$n:"
    echo "    adrp x16, bbw_p_$n"
    echo "    ldr x16, [x16, :lo12:bbw_p_$n]"
    echo "    br x16"
  done
  echo "    .bss"
  echo "    .balign 8"
  for n in $names; do
    case " $OWN " in *" $n "*) continue ;; esac
    echo "    .globl bbw_p_$n"
    echo "    .hidden bbw_p_$n"
    echo "bbw_p_$n: .quad 0"
  done
  echo '    .section .note.GNU-stack,"",%progbits'
} > "$OUT/trampolines.S"
{
  echo "// Generated by scripts/gen-vk-trampolines.sh. Do not edit."
  for n in $names; do
    case " $OWN " in *" $n "*) continue ;; esac
    echo "BBW_TRAMPOLINE($n)"
  done
} > "$OUT/trampolines.inc"
